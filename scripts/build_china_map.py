import math, json

def proj(lng, lat, w=960, h=640, pad=25):
    min_lng, max_lng = 73.5, 135.0
    min_lat, max_lat = 18.0, 53.5
    norm_x = (lng - min_lng) / (max_lng - min_lng)
    lat_rad = math.radians(lat)
    merc_n = math.log(math.tan(math.pi/4 + lat_rad/2))
    min_lat_rad = math.radians(min_lat)
    max_lat_rad = math.radians(max_lat)
    merc_min = math.log(math.tan(math.pi/4 + min_lat_rad/2))
    merc_max = math.log(math.tan(math.pi/4 + max_lat_rad/2))
    norm_y = (merc_max - merc_n) / (merc_max - merc_min)
    return round(pad + norm_x * (w - 2*pad), 1), round(pad + norm_y * (h - 2*pad), 1)

def to_path(pts):
    coords = [proj(lng, lat) for lng, lat in pts]
    d = f"M {coords[0][0]} {coords[0][1]}"
    for x, y in coords[1:]:
        d += f" L {x} {y}"
    d += " Z"
    return d

def to_line_path(pts):
    coords = [proj(lng, lat) for lng, lat in pts]
    d = f"M {coords[0][0]} {coords[0][1]}"
    for x, y in coords[1:]:
        d += f" L {x} {y}"
    return d

