/**
 * 中国区域自适应墨卡托投影算法
 * @param {number} lng 经度 (73.5° ~ 135.0°)
 * @param {number} lat 纬度 (18.0° ~ 53.5°)
 * @param {number} [viewWidth=960]
 * @param {number} [viewHeight=640]
 * @param {{minLng: number, maxLng: number, minLat: number, maxLat: number}} [bounds]
 * @returns {{x: number, y: number}}
 */
export function projectChinaGeoToSvg(lng, lat, viewWidth = 960, viewHeight = 640, bounds = null) {
  const b = bounds || {
    minLng: 73.5,
    maxLng: 135.0,
    minLat: 18.0,
    maxLat: 53.5
  }
  const normX = (lng - b.minLng) / (b.maxLng - b.minLng)
  const latRad = (lat * Math.PI) / 180
  const mercN = Math.log(Math.tan(Math.PI / 4 + latRad / 2))
  const minLatRad = (b.minLat * Math.PI) / 180
  const maxLatRad = (b.maxLat * Math.PI) / 180
  const mercMin = Math.log(Math.tan(Math.PI / 4 + minLatRad / 2))
  const mercMax = Math.log(Math.tan(Math.PI / 4 + maxLatRad / 2))
  const normY = (mercMax - mercN) / (mercMax - mercMin)
  const padX = 25
  const padY = 25
  const usableW = viewWidth - padX * 2
  const usableH = viewHeight - padY * 2
  return {
    x: Math.round((padX + normX * usableW) * 10) / 10,
    y: Math.round((padY + normY * usableH) * 10) / 10
  }
}

