const _MONTHS_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
function _enMonthYear(text) {
  return String(text)
    .replace(/(\d{4})年(\d{1,2})月/g, (all, y, m) => {
      const idx = Number(m) - 1
      return (_MONTHS_EN[idx] || m) + ' ' + y
    })
    .replace(/、/g, ', ')
}
function _enDiscount(value, suffix = '') {
  let z = parseFloat(value)
  if (!isFinite(z)) return value + ' off'
  // 中文价签存在「9.5折」与「95折」两种写法，后者需先除以 10
  if (z > 10) z = z / 10
  // 9.5 折 = 支付 95%，即优惠 5%
  const off = Math.round((10 - z) * 10 * 10) / 10
  return (off <= 0 ? 'No discount' : `${off}% off`) + suffix
}
